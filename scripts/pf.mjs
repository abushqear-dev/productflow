#!/usr/bin/env node
// Productflow state tool and hook handlers. No dependencies.
// Usage: node pf.mjs <init|start|approve|reopen|status|hook-gate|hook-session> [stage]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PLUGIN_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STAGES = {
  1: { name: 'PRD', file: 'docs/01-prd.md' },
  2: { name: 'User Stories and Use Cases', file: 'docs/02-stories.md' },
  3: { name: 'System Architecture Document', file: 'docs/03-sad.md' },
  4: { name: 'Technical Design Document', file: 'docs/04-tdd.md' },
  5: { name: 'UI/UX Study and Wireframes', file: 'docs/05-uiux.md' },
  6: { name: 'Implementation', file: 'app/' },
};
// pending -> drafting -> approved. recheck = approved earlier, invalidated by an upstream change.
const STATUSES = ['pending', 'drafting', 'approved', 'recheck'];

const projectDir = () => path.resolve(process.env.CLAUDE_PROJECT_DIR || process.cwd());
const statePath = (root) => path.join(root, '.productflow', 'state.json');
const loadState = (root) => {
  try { return JSON.parse(fs.readFileSync(statePath(root), 'utf8')); } catch { return null; }
};
const saveState = (root, state) => {
  state.updated = new Date().toISOString();
  fs.mkdirSync(path.dirname(statePath(root)), { recursive: true });
  fs.writeFileSync(statePath(root), JSON.stringify(state, null, 2) + '\n');
  fs.writeFileSync(path.join(root, 'STATUS.md'), renderStatus(state));
};

const newState = () => ({
  version: 1,
  mode: 'guided',
  stages: Object.fromEntries(Object.keys(STAGES).map((n) => [n, { status: 'pending' }])),
});

function renderStatus(state) {
  const rows = Object.entries(STAGES).map(([n, s]) =>
    `| ${n} | ${s.name} | ${state.stages[n].status} | ${s.file} |`);
  return [
    '# Productflow status',
    '',
    '<!-- Generated by scripts/pf.mjs. Do not edit by hand; the source of truth is .productflow/state.json. -->',
    '',
    `Mode: ${state.mode} · Updated: ${state.updated}`,
    '',
    '| Stage | Document | Status | File |',
    '|-------|----------|--------|------|',
    ...rows,
    '',
    `Next: ${nextAction(state)}`,
    '',
  ].join('\n');
}

function nextAction(state) {
  for (const n of Object.keys(STAGES)) {
    const st = state.stages[n].status;
    if (st !== 'approved') return `Stage ${n} (${STAGES[n].name}) is ${st}.`;
  }
  return 'All stages approved.';
}

const fail = (msg, code = 1) => { process.stderr.write(msg + '\n'); process.exit(code); };
const requireState = (root) => loadState(root) || fail('Not a Productflow project. Run init.');
const stageArg = (arg) => {
  if (!STAGES[arg]) fail(`Stage must be 1-6, got "${arg}".`);
  return String(arg);
};
const firstUnapprovedBefore = (state, n) =>
  Object.keys(STAGES).find((k) => Number(k) < Number(n) && state.stages[k].status !== 'approved');

const commands = {
  init() {
    const root = projectDir();
    for (const dir of ['docs/input', 'docs']) fs.mkdirSync(path.join(root, dir), { recursive: true });
    for (const f of ['ASSUMPTIONS.md', 'TRACE.md']) {
      const dest = path.join(root, f);
      if (!fs.existsSync(dest)) fs.copyFileSync(path.join(PLUGIN_ROOT, 'templates', f), dest);
    }
    const state = loadState(root) || newState();
    saveState(root, state);
    console.log(`Productflow initialised in ${root}. ${nextAction(state)}`);
  },

  start(arg) {
    const root = projectDir(); const state = requireState(root);
    const n = stageArg(arg);
    const blocker = firstUnapprovedBefore(state, n);
    if (blocker) fail(`Cannot start stage ${n}: stage ${blocker} (${STAGES[blocker].name}) is not approved.`);
    if (state.stages[n].status === 'approved') fail(`Stage ${n} is already approved. Use reopen after the user agrees to an upstream change.`);
    state.stages[n].status = 'drafting';
    saveState(root, state);
    console.log(`Stage ${n} (${STAGES[n].name}) is now drafting.`);
  },

  approve(arg) {
    const root = projectDir(); const state = requireState(root);
    const n = stageArg(arg);
    const blocker = firstUnapprovedBefore(state, n);
    if (blocker) fail(`Cannot approve stage ${n}: stage ${blocker} is not approved.`);
    if (n !== '6' && !fs.existsSync(path.join(root, STAGES[n].file))) fail(`Cannot approve stage ${n}: ${STAGES[n].file} does not exist.`);
    state.stages[n].status = 'approved';
    state.stages[n].approvedAt = new Date().toISOString();
    saveState(root, state);
    console.log(`Stage ${n} (${STAGES[n].name}) approved. ${nextAction(state)}`);
  },

  // Called only after the user agrees to revise an approved document (upstream-change rule).
  reopen(arg) {
    const root = projectDir(); const state = requireState(root);
    const n = stageArg(arg);
    state.stages[n].status = 'drafting';
    for (const k of Object.keys(STAGES)) {
      if (Number(k) > Number(n) && state.stages[k].status === 'approved') state.stages[k].status = 'recheck';
    }
    saveState(root, state);
    console.log(`Stage ${n} reopened. Later approved stages are marked recheck.`);
  },

  status() {
    const root = projectDir(); const state = requireState(root);
    saveState(root, state);
    console.log(renderStatus(state));
  },

  // PreToolUse hook on Write|Edit|MultiEdit. Exit 2 blocks the call and shows stderr to the model.
  'hook-gate'() {
    let input = {};
    try { input = JSON.parse(fs.readFileSync(0, 'utf8')); } catch { process.exit(0); }
    const root = path.resolve(input.cwd || projectDir());
    const state = loadState(root);
    if (!state) process.exit(0);
    const target = input.tool_input?.file_path;
    if (!target) process.exit(0);
    const rel = path.relative(root, path.resolve(root, target)).split(path.sep).join('/');
    if (rel.startsWith('..')) process.exit(0);

    if (rel === 'STATUS.md' || rel.startsWith('.productflow/')) {
      fail('Productflow: STATUS.md and .productflow/ are managed by scripts/pf.mjs. Use its commands (start, approve, reopen) instead of editing them.', 2);
    }
    const doc = rel.match(/^docs\/0([1-5])-[^/]+\.md$/);
    if (doc) {
      const n = doc[1];
      const blocker = firstUnapprovedBefore(state, n);
      if (blocker) fail(`Productflow: stage ${blocker} (${STAGES[blocker].name}) is not approved, so stage ${n} cannot be written yet. The order is fixed.`, 2);
      if (state.stages[n].status === 'approved') fail(`Productflow: ${rel} is approved and handed off. Do not edit it silently. Stop, tell the user what you found, and ask whether to revise it (upstream-change skill).`, 2);
    }
    if (rel.startsWith('app/')) {
      const blocker = firstUnapprovedBefore(state, '6');
      if (blocker) fail(`Productflow: implementation cannot start until all five documents are approved. Stage ${blocker} (${STAGES[blocker].name}) is ${state.stages[blocker].status}.`, 2);
    }
    process.exit(0);
  },

  // SessionStart hook: stdout is added to the session context.
  'hook-session'() {
    const root = projectDir();
    const state = loadState(root);
    if (!state) return;
    console.log(`Productflow project detected (${state.mode} mode). ${nextAction(state)} Run /productflow:product to continue. Load the productflow:product skill before doing any product-document work.`);
  },
};

const [cmd, arg] = process.argv.slice(2);
if (!commands[cmd]) fail(`Unknown command "${cmd}". Commands: ${Object.keys(commands).join(', ')}.`);
commands[cmd](arg);
